print(12, 34) # usamos virgulas para adicionar mais argumentos para imprimir 
print(56, 78) # são argumentos não nomeados

print(12, 34, sep='-') #usando sep = separação, podemos separas cada argumeto com algo escrito entre aspas
print(56, 78, sep= "-") # pode ser utilizado tanto aspas ' quanto as ''

print(12, 34, sep= "-", end='\r\n') # end é usado para usar algum argumento no final de cada qubra de linha
print(56, 78, sep= "-", end='#')