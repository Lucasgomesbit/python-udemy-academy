#Dado bool (boolean) -> Possuem apenas dois valores (True or False)
# == -> Operador logico que questiona se um valor é igual ao outro
# Exemplos:
print(10 == 10) # A resposta é True 
print(10 == 11) # A resposta é False 
print ('red' == 'red') # A resposta é True 
print('Blue'== 'blue') # A resposta é False